    "### 2.3 Estrategia 2: Imputación por K-Vecinos Más Cercanos (KNN)\n",
    "\n",
    "#### Descripción\n",
    "\n",
    "La imputación por K-Vecinos Más Cercanos (K-Nearest Neighbors, KNN) es una técnica que estima los valores faltantes basándose en la similitud con otras observaciones completas. Para cada valor faltante, el algoritmo:\n",
    "\n",
    "1. Identifica las K observaciones más similares (vecinos) que tienen valores completos\n",
    "2. Calcula la distancia entre observaciones usando las variables disponibles\n",
    "3. Imputa el valor faltante como el promedio (ponderado o no) de los valores de los K vecinos más cercanos\n",
    "\n",
    "#### Ventajas\n",
    "- Considera las relaciones multivariadas entre las características\n",
    "- Puede capturar patrones no lineales en los datos\n",
    "- Más precisa que la imputación por media cuando existen correlaciones fuertes\n",
    "\n",
    "#### Desventajas\n",
    "- Computacionalmente costosa para conjuntos de datos grandes\n",
    "- Sensible a la escala de las variables (requiere normalización)\n",
    "- La elección de K puede afectar significativamente los resultados\n",
    "- No funciona bien con alta dimensionalidad\n",
    "\n",
    "#### Casos de Uso Recomendados\n",
    "- Cuando existe correlación entre las variables\n",
    "- Conjuntos de datos de tamaño pequeño a mediano\n",
    "- Cuando los datos faltan de manera aleatoria (MAR)\n",
    "- En problemas donde la similitud entre observaciones es significativa"
