    "### 2.2 Estrategia 1: Imputación por Media, Mediana o Moda\n",
    "\n",
    "#### Descripción\n",
    "\n",
    "Esta estrategia consiste en reemplazar los valores faltantes con medidas de tendencia central calculadas a partir de los valores observados. La elección entre media, mediana o moda depende del tipo de variable y la distribución de los datos.\n",
    "\n",
    "- **Media:** Para variables numéricas con distribución aproximadamente normal\n",
    "- **Mediana:** Para variables numéricas con distribución sesgada o presencia de valores atípicos\n",
    "- **Moda:** Para variables categóricas o discretas\n",
    "\n",
    "#### Ventajas\n",
    "- Implementación simple y rápida\n",
    "- Preserva el tamaño de la muestra\n",
    "- No introduce valores fuera del rango observado\n",
    "\n",
    "#### Desventajas\n",
    "- Reduce la variabilidad de los datos\n",
    "- No considera las relaciones entre variables\n",
    "- Puede introducir sesgo si los datos no faltan aleatoriamente\n",
    "\n",
    "#### Casos de Uso Recomendados\n",
    "- Cuando el porcentaje de datos faltantes es bajo (< 5%)\n",
    "- En análisis exploratorios preliminares\n",
    "- Cuando se requiere una solución rápida y los datos faltan completamente al azar (MCAR)"
